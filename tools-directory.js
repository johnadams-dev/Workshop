// tools-directory.js — shared tool/resource metadata for search + the
// feedback.html tool picker.
//
// Plain global array, no bundler/modules (matches this repo's convention —
// every page is a self-contained <script> tag). Loaded via a plain
// <script src="./tools-directory.js"> from index.html and feedback.html.
//
// Two kinds of entries, distinguished by `kind`:
//
//   kind: 'workshop' — one of the Workshop's own ~30 built tools. `slug`/
//   `name`/`description`/`url` are sourced verbatim from index.html's
//   static cards (the single source of truth for that copy). `slug` is
//   the identity key feedback.html's tool picker uses — it matches each
//   page's *actual* outbound `?tool=` Feedback-link value, which is not
//   always the page's base filename (e.g. lockbox-app.html deliberately
//   sends `?tool=lockbox`, not `?tool=lockbox-app`, and that's already
//   self-consistent — left as-is). Two real slug/URL mismatches were found
//   and fixed here: hotsheet-v2.html was sending `?tool=hotsheet-v2` while
//   feedback.html only recognized `hotsheet`, and agent-notices.html was
//   sending `?tool=agent-notices` while feedback.html only recognized
//   `market-notices` — both silently failed to preselect the tool before
//   this fix. `feedbackGroup` is null for a handful of tools that have
//   never had a feedback.html entry (Feedback & Support itself, Workshop
//   Guide, Agent Roster, Cameron's Stage — Outside Listings) — left that
//   way deliberately rather than expanding feedback.html's picker beyond
//   the verified drift this file was built to fix.
//
//   kind: 'resource' — an ACC company-wide resource, NOT one of the
//   Workshop's own tools. First-pass transcription from a PDF ("ACC
//   Tools") the user provided on 2026-08-27, itself a snapshot of the
//   accagents.com / ACCAgents intranet (sites.google.com/adamscameron.com/
//   agent-portal-v2) — which the user says is not necessarily current and
//   plans to keep editing directly going forward. THIS IS NOT A LIVE SYNC.
//   Treat this block as a starting point to hand-edit, not a source of
//   truth — a live Google Sites pull was already attempted and doesn't
//   work (see Server/docs/agent-hub-plan.md Step 2).
//     - `url` is only ever a confirmed real address: either stated
//       directly in the PDF's prose, or already verified in agent-hub.html's
//       own hand-curated INTRANET_LINKS/FRED_URL/MCFL_URL/AC_SOCIAL_URL/
//       ASK_CAMERON_URL consts. Never guessed — an entry with no confirmed
//       address ships with `url: null` and renders as text-only wherever
//       it's shown, rather than as a dead or wrong link.
//     - `tags` are approximate/topical (not a precise transcription of the
//       PDF's per-row checkbox columns, which don't survive PDF-to-text
//       extraction reliably) — folded into the same searchable text as
//       `name`+`description`, not used for any dedicated filter UI.
//     - Tools ACC's own Workshop already builds (Cameron's Lens, Cameron's
//       Stage, Foundation, Pathfinder, the Contract Date Calculator/"Date
//       Calculation Tool", Agent Roster) are deliberately NOT repeated here
//       — they're already present as `kind: 'workshop'` entries above.
//     - A few PDF rows have no explanatory prose at all (Tallahassee MLS,
//       Naples MLS, Beaches MLS) — included anyway as minimal stubs rather
//       than dropped, since the user can flesh these out by hand later.

